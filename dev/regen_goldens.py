#!/usr/bin/env python3
"""
Regenerate the golden translation files.

Run this locally (never CI — it needs the model). When mlx-lm or the model
revision changes and the output legitimately shifts, regenerate and READ THE
DIFF: that review is the quality gate these files exist for.

    .venv/bin/python3 dev/regen_goldens.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from dich import backend  # noqa: E402

GOLDEN_DIR = ROOT / "tests" / "golden"


def _mlx_lm_version() -> str:
    try:
        from importlib.metadata import version

        return version("mlx-lm")
    except Exception:  # noqa: BLE001
        return "unknown"


def main() -> int:
    cases = json.loads((GOLDEN_DIR / "cases.json").read_text(encoding="utf-8"))
    header = (
        f"<!-- generated by dev/regen_goldens.py · app {backend.VERSION} · "
        f"model {backend.MODEL_NAME} · mlx-lm {_mlx_lm_version()} -->"
    )
    for name, source in sorted(cases.items()):
        result = backend.translate_text(source, use_cache=False)
        path = GOLDEN_DIR / f"{name}.golden.md"
        path.write_text(header + "\n" + result.text.strip() + "\n", encoding="utf-8")
        print(
            f"{name}: {result.words_in} -> {result.words_out} words, "
            f"{result.tokens_out} tokens, {result.elapsed:.1f}s"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
